import imports from "lucide-react/dynamicIconImports.js";
import { readFileSync, writeFileSync } from "node:fs";

const target = new URL(
  "../../internal/domain/playlist_icons_generated.go",
  import.meta.url,
);
const names = Object.keys(imports).sort();
const source = `// Code generated by web/scripts/playlist-icons.mjs; DO NOT EDIT.
// SPDX-License-Identifier: GPL-2.0-or-later
package domain

var playlistIconNames = map[string]bool{
${names.map((name) => `\t${JSON.stringify(name)}: true,`).join("\n")}
}
`;
if (process.argv.includes("--check")) {
  if (
    readFileSync(target, "utf8").replace(/\s/g, "") !==
    source.replace(/\s/g, "")
  ) {
    throw new Error(
      "Playlist icon catalog is stale. Run npm run icons:generate in web.",
    );
  }
} else {
  writeFileSync(target, source);
}
console.log(`Playlist icon catalog: ${names.length} names`);
